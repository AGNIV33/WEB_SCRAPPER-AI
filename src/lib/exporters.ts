"use client";
/* Export the analysis in many formats. Everything runs in the browser (no server needed). */
import { contrast, type PageResult, type SiteResult, type Summary } from "./report";
import type { AiResult } from "@/components/Dashboard";

export type ExportData = { pages: PageResult[]; site: SiteResult | null; summary: Summary; ai: AiResult | null; meta: { startedAt: Date; seconds: number } | null };

const host = (d: ExportData) => { try { return new URL(d.summary.url || d.pages[0].url).hostname; } catch { return "site"; } };
const stamp = (d: ExportData) => (d.meta?.startedAt || new Date()).toISOString().slice(0, 10);
const fname = (d: ExportData, ext: string) => `${host(d)}-report-${stamp(d)}.${ext}`;
const pathOf = (u: string) => { try { const x = new URL(u); return x.pathname + x.search; } catch { return u; } };
const ok = (d: ExportData) => d.pages.filter((p) => !p.error);

export function saveBlob(name: string, blob: Blob) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 5000);
}
const saveText = (name: string, text: string, type: string) => saveBlob(name, new Blob([text], { type }));

/* ---------------- Markdown (full report) ---------------- */
export function buildReportMd(d: ExportData) {
  const s = d.summary, L: string[] = [];
  const row = (...c: (string | number | null | undefined)[]) => `| ${c.map((x) => String(x ?? "—").replace(/\|/g, "/").replace(/\n/g, " ")).join(" | ")} |`;
  L.push(`# Website report: ${host(d)}`, "", `- **URL:** ${s.url}`, `- **Analyzed:** ${(d.meta?.startedAt || new Date()).toLocaleString()}${d.meta ? ` (took ${d.meta.seconds.toFixed(1)}s)` : ""}`, `- **Generated by:** Scrapper AI`, "");
  L.push("## Scores", "", "| Metric | Value |", "|---|---|", row("Pages analyzed", s.pagesAnalyzed), row("Pages failed", s.pagesFailed), row("Security score", `${s.security.score}/100`), row("SEO score", `${s.seoScore}/100`), row("Average load time", `${(s.performance.avgLoadMs / 1000).toFixed(1)}s`), row("Broken links", `${s.brokenLinks.length} of ${s.linksChecked}`), "");
  if (d.ai?.suggestions?.length) {
    L.push("## Suggestions", "", "| Priority | Area | Suggestion | Detail |", "|---|---|---|---|");
    d.ai.suggestions.forEach((x) => L.push(row(x.priority, x.area, x.title, x.detail)));
    L.push("");
  }
  L.push("## Colours", "", "| Role | Hex | Share |", "|---|---|---|");
  s.palette.backgrounds.forEach((c) => L.push(row("Background", c.value, `${c.share}%`)));
  s.palette.text.forEach((c) => L.push(row("Text", c.value, `${c.share}%`)));
  s.palette.borders.forEach((c) => L.push(row("Border", c.value, `${c.share}%`)));
  s.palette.accents.forEach((c) => L.push(row("Accent", c, "")));
  L.push("", "## Fonts", "", "| Family | Share |", "|---|---|", ...s.typography.families.map((f) => row(f.value, `${f.share}%`)), "", `**Sizes:** ${s.typography.sizes.map((x) => x.value).join(", ")}`, "", `**Weights:** ${s.typography.weights.map((x) => x.value).join(", ")}`, "");
  L.push("## Pages", "", "| # | URL | Status | Title | Words | Images (no alt) | Load | Size |", "|---|---|---|---|---|---|---|---|");
  d.pages.forEach((p, i) => L.push(row(i + 1, p.url, p.error ? "error" : p.status, p.seo?.title, p.seo?.wordCount, p.seo ? `${p.seo.images} (${p.seo.imagesNoAlt})` : null, p.perf ? `${p.perf.load}ms` : null, p.perf ? `${p.perf.transferKB} KB` : null)));
  L.push("");
  d.pages.forEach((p) => {
    L.push(`### ${p.seo?.title || p.url}`, "", `- URL: ${p.url}`);
    if (p.error) { L.push(`- Error: ${p.error}`, ""); return; }
    L.push(`- Description: ${p.seo?.description || "—"}`, `- H1: ${p.seo?.h1.join(" / ") || "—"}`, `- H2: ${p.seo?.h2.slice(0, 8).join(" / ") || "—"}`, `- Fonts: ${p.typography?.families.map(([f]) => f).join(", ") || "—"}`, `- Tech: ${p.tech?.map((t) => t.name).join(", ") || "—"}`, `- Structured data: ${p.seo?.jsonLd.join(", ") || "none"}`);
    const issues = s.seo.pages.find((x) => x.url === p.url)?.issues || [];
    if (issues.length) L.push(`- SEO issues: ${issues.join("; ")}`);
    L.push("");
  });
  L.push("## Animations", "", `- Libraries: ${s.animations.libraries.map((l) => l.name + (l.version ? " " + l.version : "")).join(", ") || "none"}`, `- @keyframes: ${s.animations.keyframes.join(", ") || "none"}`, `- Elements with transitions: ${s.animations.transitionElements}`, "");
  L.push("## Security (passive checks)", "", "| Check | Result | Severity | Detail |", "|---|---|---|---|", ...s.security.checks.map((c) => row(c.name, c.ok ? "Pass" : "Fail", c.severity, c.detail)), "");
  if (s.security.libIssues.length) L.push("**Outdated libraries:**", "", ...s.security.libIssues.map((i) => `- ${i.library} ${i.version}: ${i.issue}. ${i.fix}.`), "");
  if (s.security.mixedContent.length) L.push("**Mixed content:**", "", ...s.security.mixedContent.map((m) => `- ${m}`), "");
  if (s.security.cookies.length) L.push("**Cookies:**", "", "| Name | Secure | HttpOnly | SameSite |", "|---|---|---|---|", ...s.security.cookies.map((c) => row(c.name, c.secure ? "yes" : "no", c.httpOnly ? "yes" : "no", c.sameSite)), "");
  L.push("## Broken links", "", ...(s.brokenLinks.length ? s.brokenLinks.map((b) => `- ${b.url} (${b.status ?? b.error})`) : ["None found."]), "");
  L.push("## Tech stack", "", ...s.tech.map((t) => `- ${t.name}${t.version ? " " + t.version : ""}`), ...s.hosting.map((h) => `- ${h}`), "");
  if (d.ai?.designMd) L.push("---", "", "# Appendix: design.md", "", d.ai.designMd);
  L.push("", "---", "", `*Report generated by Scrapper AI on ${(d.meta?.startedAt || new Date()).toLocaleDateString()}. Created by ${CREATOR}.*`);
  return L.join("\n");
}

