function loadImg(src: string): Promise<HTMLImageElement> {
  return new Promise((res, rej) => { const i = new Image(); i.onload = () => res(i); i.onerror = rej; i.src = src; });
}
/** Crops the top of a screenshot to a given width:height ratio (so it fills the space exactly, no blank areas). */
async function cropTop(src: string, maxRatio: number): Promise<{ data: string; ratio: number }> {
  const img = await loadImg(src);
  const h = Math.min(img.height, Math.round(img.width * maxRatio));
  const c = document.createElement("canvas");
  c.width = img.width; c.height = h;
  c.getContext("2d")!.drawImage(img, 0, 0, img.width, h, 0, 0, img.width, h);
  return { data: c.toDataURL("image/jpeg", 0.82), ratio: h / img.width };
}
/** Renders the creator's signature with the app's handwriting font (if loaded) into a PNG. */
function signatureImage(text: string): { data: string; ratio: number } | null {
  try {
    const probe = document.createElement("span");
    probe.className = "font-signature"; probe.style.position = "absolute"; probe.style.opacity = "0"; probe.textContent = text;
    document.body.appendChild(probe);
    const family = getComputedStyle(probe).fontFamily || "cursive";
    probe.remove();
    const c = document.createElement("canvas");
    const ctx = c.getContext("2d")!;
    ctx.font = `700 96px ${family}`;
    const w = Math.ceil(ctx.measureText(text).width) + 40;
    c.width = w; c.height = 150;
    ctx.font = `700 96px ${family}`;
    ctx.fillStyle = "#1e3a8a";
    ctx.textBaseline = "middle";
    ctx.fillText(text, 20, 78);
    return { data: c.toDataURL("image/png"), ratio: c.height / c.width };
  } catch { return null; }
}

