export function exportCsv(d: ExportData) {
  const esc = (v: unknown) => { const t = String(v ?? ""); return /[",\n]/.test(t) ? `"${t.replace(/"/g, '""')}"` : t; };
  const head = ["URL", "Status", "Title", "Description", "H1", "Words", "Images", "Images without alt", "Links", "Load ms", "Requests", "Size KB", "Fonts", "SEO issues"];
  const rows = d.pages.map((p) => [p.url, p.error ? "error" : p.status, p.seo?.title, p.seo?.description, p.seo?.h1.join(" / "), p.seo?.wordCount, p.seo?.images, p.seo?.imagesNoAlt, p.links?.length, p.perf?.load, p.perf?.requests, p.perf?.transferKB, p.typography?.families.map(([f]) => f).join(", "), d.summary.seo.pages.find((x) => x.url === p.url)?.issues.join("; ")]);
  saveText(fname(d, "csv"), "﻿" + [head, ...rows].map((r) => r.map(esc).join(",")).join("\r\n"), "text/csv");
}

