/** jsPDF's built-in fonts only cover Latin-1, so map common symbols and replace the rest. */
const PDF_MAP: Record<string, string> = { "✅": "[ok]", "❌": "[x]", "✓": "v", "→": "->", "←": "<-", "≤": "<=", "≥": ">=", "—": "-", "–": "-", "…": "...", "‘": "'", "’": "'", "“": '"', "”": '"', "•": "-", "·": "-" };
const clean = (v: unknown) => String(v ?? "").replace(/[^\x00-\xFF]/gu, (c) => PDF_MAP[c] ?? "?");

